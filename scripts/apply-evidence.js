// Turn the corpus evidence matrix (research/corpus/evidence_matrix.json) into
// lexicon adjustments: src/engine/evidence-lexicon.js
//
// For every keyword term (curated from core papers + POUH):
//   support  = papers in the corpus whose finding points the same way as the
//              term's shape (rising → '+', falling → '−', band → nonlinear/any)
//   against  = papers pointing the opposite way
//   factor   = 0.8 + 0.6 · log(1 + support) / log(1 + maxSupport)   (0.8 … 1.4)
//              0.8 when the abstracts are silent (absence ≠ evidence against),
//              0.6 on a real conflict (≥ 2 papers against, more than for),
//              never below 1 for POUH-methodology terms (the user's own method).
// Features the corpus links to a keyword (≥ 3 papers, |consistency| ≥ 0.5)
// that the curated lexicon lacks are added as new monotone terms.
//
// usage: node scripts/apply-evidence.js [research/corpus/evidence_matrix.json]

import { readFileSync, writeFileSync } from 'node:fs';
import { KEYWORDS_CURATED } from '../src/engine/keywords.js';
import { FEATURES } from '../src/engine/metrics.js';

const src = process.argv[2] || new URL('../research/corpus/evidence_matrix.json', import.meta.url);
const M = JSON.parse(readFileSync(src));
const INF = 1e9;
const RANGE = Object.fromEntries(FEATURES.map((f) => [f.key, f.range]));

const shapeOf = ([a, , , d]) => (d >= INF ? 'rising' : a <= -INF ? 'falling' : 'band');

// Aggregate matrix cells onto engine features per keyword.
function featureEvidence(kw) {
  const out = {};
  for (const [param, c] of Object.entries(M.cells[kw] || {})) {
    if (!c.engine) continue;
    const e = (out[c.engine] ||= { pos: 0, neg: 0, nonlinear: 0, papers: new Set(), params: [], ranges: [] });
    // sign −1: e.g. traffic volume ↑ ≡ distance to road ↓
    e.pos += c.sign > 0 ? c.pos : c.neg;
    e.neg += c.sign > 0 ? c.neg : c.pos;
    e.nonlinear += c.nonlinear;
    c.papers.forEach((p) => e.papers.add(p));
    e.params.push(param);
    e.ranges.push(...(c.ranges || []).map((r) => ({ ...r, param })));
  }
  return out;
}

let maxSupport = 1;
const plan = {};
for (const [kw, def] of Object.entries(KEYWORDS_CURATED)) {
  const ev = featureEvidence(kw);
  plan[kw] = { ev, terms: [] };
  for (const t of def.terms) {
    const e = ev[t.f];
    const shape = shapeOf(t.t);
    let support = 0, against = 0;
    if (e) {
      if (shape === 'rising') { support = e.pos; against = e.neg; }
      else if (shape === 'falling') { support = e.neg; against = e.pos; }
      else { support = e.nonlinear + Math.min(e.pos, e.neg) + Math.max(e.pos, e.neg) * 0.5; against = 0; }
    }
    maxSupport = Math.max(maxSupport, support);
    plan[kw].terms.push({ f: t.f, shape, support, against, pouh: (t.src || []).includes('pouh2022'), papers: e ? [...e.papers].slice(0, 12) : [] });
  }
}

const out = {};
for (const [kw, def] of Object.entries(KEYWORDS_CURATED)) {
  const { ev, terms } = plan[kw];
  const adj = terms.map((t) => {
    const conflict = t.against > t.support && t.against >= 2;
    let factor = conflict ? 0.6 : 0.8 + (0.6 * Math.log1p(t.support)) / Math.log1p(maxSupport);
    if (t.pouh) factor = Math.max(1, factor);
    return { f: t.f, factor: +factor.toFixed(3), support: t.support, against: t.against, conflict, papers: t.papers };
  });
  const have = new Set(def.terms.map((t) => t.f));
  const added = [];
  for (const [f, e] of Object.entries(ev)) {
    if (have.has(f)) continue;
    const n = e.papers.size, dir = e.pos + e.neg;
    const cons = dir ? (e.pos - e.neg) / dir : 0;
    if (n < 3 || Math.abs(cons) < 0.5 || dir < 3) continue;
    const [lo, hi] = RANGE[f];
    const span = hi - lo;
    const t = cons > 0 ? [lo + 0.1 * span, lo + 0.5 * span, INF, INF] : [-INF, -INF, lo + 0.5 * span, lo + 0.9 * span];
    added.push({
      f, t: t.map((v) => +v.toFixed(3)), w: +(0.25 + 0.25 * Math.log1p(n) / Math.log1p(maxSupport)).toFixed(3),
      src: [`corpus:${n}`], n, consistency: +cons.toFixed(2), params: e.params, papers: [...e.papers].slice(0, 12),
    });
  }
  out[kw] = { adjust: adj, added };
}

const summary = { papers: M.papers, relevant: M.relevant, findings: M.findings, maxSupport };
writeFileSync(new URL('../src/engine/evidence-lexicon.js', import.meta.url),
  `// Generated by scripts/apply-evidence.js from the ${M.papers}-paper corpus evidence matrix. Do not edit.\n` +
  `export const EVIDENCE_SUMMARY = ${JSON.stringify(summary)};\n` +
  `export const EVIDENCE_LEXICON = ${JSON.stringify(out, null, 1)};\n`);
for (const [kw, o] of Object.entries(out)) {
  console.log(kw.padEnd(12), o.adjust.map((a) => `${a.f}×${a.factor}${a.conflict ? '!' : ''}(${a.support}/${a.against})`).join(' '),
    o.added.length ? ' + ' + o.added.map((a) => `${a.f}[${a.consistency > 0 ? '+' : '−'}${a.n}]`).join(' ') : '');
}

// Compact bundle for the app's proof panel: per keyword, every parameter the
// corpus links to it (computable or not), with counts and paper titles.
const titles = new Map(readFileSync(new URL('../research/corpus/papers.jsonl', import.meta.url), 'utf8').trim().split('\n')
  .map((l) => JSON.parse(l)).map((p) => [p.id, [p.t, p.y, p.doi || null, (p.a || [])[0] || '']]));
const used = new Set();
const lite = {};
for (const [kw, row] of Object.entries(M.cells)) {
  lite[kw] = Object.entries(row)
    .filter(([, c]) => c.n >= 2)
    .sort((a, b) => b[1].n - a[1].n)
    .slice(0, 25)
    .map(([p, c]) => {
      const papers = c.papers.slice(0, 6);
      papers.forEach((id) => used.add(id));
      return { p, n: c.n, pos: c.pos, neg: c.neg, nl: c.nonlinear, engine: c.engine, papers, q: c.quotes.slice(0, 2), ranges: c.ranges.slice(0, 4) };
    });
}
const notYet = Object.fromEntries(M.parameters.filter(([p]) => !M.engineMap[p]).slice(0, 40));
writeFileSync(new URL('../public/data/evidence-matrix.json', import.meta.url), JSON.stringify({
  summary: { papers: M.papers, relevant: M.relevant, findings: M.findings },
  methods: M.methods.slice(0, 22), outcomes: M.outcomes.slice(0, 22),
  keywords: lite, notYetComputable: notYet,
  papers: Object.fromEntries([...used].filter((id) => titles.has(id)).map((id) => [id, titles.get(id)])),
}));
console.log(`evidence-matrix.json: ${used.size} papers referenced`);
